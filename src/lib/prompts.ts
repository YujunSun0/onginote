function imageNote(m: ChatMessage): string {
  const n = messageImages(m).length;
  return n ? ` [대화 캡처 이미지 ${n}장 첨부]` : "";
}

export function transcript(messages: ChatMessage[], max = 16): string {
  return messages
    .slice(-max)
    .map((m) => `${m.role === "user" ? "사용자" : "캐릭터"}: ${splitBubbles(m.text).join(" ")}${imageNote(m)}`)
    .join("\n");
}

