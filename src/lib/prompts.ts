export function personContext(person: Person | null): string {
  if (!person) return "[상담 대상] 특정 인물 없이 사용자 자신의 이야기.";
  const lines = [
    `[상담 대상 인물 프로필: 사용자가 직접 기록한 정보]`,
    `이름(별명): ${person.name} / 관계: ${person.relation}`,
    person.mbti && `MBTI: ${person.mbti}`,
    person.age && `나이: ${person.age}`,
    person.birthday && `생일: ${person.birthday}`,
    person.likes.length > 0 && `좋아하는 것: ${person.likes.join(", ")}`,
    person.dislikes.length > 0 && `싫어하는 것: ${person.dislikes.join(", ")}`,
    person.contactStyle && `연락 스타일: ${person.contactStyle}`,
    person.notes.length > 0 && `성격 메모: ${person.notes.join(" / ")}`,
    person.timeline.length > 0 &&
      `지난 일: ${person.timeline.map((t) => `${t.date} ${t.text}`).join(" / ")}`,
  ].filter(Boolean);
  lines.push("이 정보는 관련 있을 때만 자연스럽게 활용해. 프로필을 줄줄 읊지 마.");
  return lines.join("\n");
}

/** 세션 동안 바뀌지 않는 시스템 프롬프트 (프롬프트 캐싱 대상). */
export function buildSystemPrompt(character: Character, person: Person | null): string {
  return [SAFETY_RULES, `[캐릭터]\n${character.persona}`, personContext(person)].join("\n\n");
}

